def validate_puzzle(question, answer):
    import re
    normalized_question = " ".join(re.sub(r"[+|،,:؛]+", " ", question.lower()).split())
    normalized_answer = " ".join(str(answer).lower().split())
    return bool("+" in question and normalized_answer not in normalized_question)
