used_riddles = set()          # سازگاری با کد قدیمی؛ دیگر مبنای انتخاب نیست
_SEEN_BY_USER = {}
_FALLBACK_TOKENS = count(1)

# فایلِ ماندگارِ تاریخچهٔ چیستان‌های دیده‌شدهٔ هر کاربر، تا بعد از ری‌استارت
# ربات هم حفظ شود.
_PROGRESS_FILE = runtime_config_file("riddle_progress.json")
_PROGRESS_STORE = SeenProgressStore("riddle_progress", _PROGRESS_FILE, _SEEN_BY_USER)


def _load_progress():
    if _PROGRESS_STORE.sqlite:
        return
    try:
        if _PROGRESS_FILE.exists():
            data = json.loads(_PROGRESS_FILE.read_text(encoding="utf-8"))
            if isinstance(data, dict):
                for k, v in data.items():
                    _SEEN_BY_USER.setdefault(k, set(v or ()))
    except (OSError, ValueError):
        pass


def _save_progress(user_key=None, values=None):
    if _PROGRESS_STORE.sqlite:
        if user_key is not None:
            if values is None:
                _PROGRESS_STORE.mark(user_key)
            else:
                _PROGRESS_STORE.replace(user_key, values)
        return
    try:
        data = {k: sorted(v) for k, v in _SEEN_BY_USER.items()}
        write_json(_PROGRESS_FILE, data)
    except OSError:
        pass


_load_progress()


def _next_token():
    """توکن یکتا که با ری‌استارت ربات تکرار نمی‌شود.

    شمارندهٔ حافظه‌ای با هر ری‌استارت از ۱ شروع می‌شد و مرجع جایزه را
    تکراری می‌کرد، پس دفتر تراکنش پرداخت را رد می‌کرد و کاربر سکه‌ای
    نمی‌گرفت. حالا از شمارندهٔ ماندگار اقتصاد استفاده می‌شود.
    """
    try:
        from economy import rewards as _rewards
        return _rewards.round_id()
    except Exception:
        # اگر اقتصاد در دسترس نبود، بازی نباید بخوابد.
        return next(_FALLBACK_TOKENS)


_RANDOM = random.SystemRandom()
RIDDLE_TIMEOUT = 50


def _user_key(user_id):
    return str(user_id)


def _seen(user_id):
    key = _user_key(user_id)
    if _PROGRESS_STORE.sqlite:
        return _PROGRESS_STORE.get(key)
    return _SEEN_BY_USER.setdefault(key, set())


def seen_count(user_id):
    return len(_seen(user_id))


def remaining_count(user_id):
    return max(len(RIDDLES) - seen_count(user_id), 0)


def reset_user(user_id=None):
    if user_id is None:
        if _PROGRESS_STORE.sqlite:
            _PROGRESS_STORE.clear()
        else:
            _SEEN_BY_USER.clear()
            _save_progress()
        return
    key = _user_key(user_id)
    if _PROGRESS_STORE.sqlite:
        _PROGRESS_STORE.delete(key)
    else:
        _SEEN_BY_USER.pop(key, None)
        _save_progress()


def reset_all():
    """پاک‌سازی کامل — برای تست و ری‌استارت."""
    active_riddles.clear()
    used_riddles.clear()
    if _PROGRESS_STORE.sqlite:
        _PROGRESS_STORE.clear()
    else:
        _SEEN_BY_USER.clear()
        _save_progress()


def _norm(value):
    return (
        str(value or "").strip()
        .replace("ي", "ی").replace("ك", "ک")
        .replace("\u200c", "").replace(" ", "")
    )


def new_riddle(chat_id, user_id):
    """چیستان تازه‌ای که این کاربر ندیده است.

    اگر کاربر همهٔ چیستان‌ها را دیده باشد، دور او از نو باز می‌شود (بازی
    چیستان محدودیت دائمی ندارد؛ فقط تکرار درون یک دور ممنوع است).
    """
    key = _user_key(user_id)
    seen = _seen(user_id)
    remaining = [item for item in RIDDLES if item[0] not in seen]
    if not remaining:
        seen.clear()
        remaining = list(RIDDLES)

    question, answer = _RANDOM.choice(remaining)
    seen.add(question)
    used_riddles.add(RIDDLES.index((question, answer)))
    _save_progress(key, seen)

    active_riddles[(chat_id, user_id)] = {
        "question": question,
        "answer": answer,
        "token": _next_token(),
        "time": time.time(),
    }
    return question


def get_token(chat_id, user_id):
    data = active_riddles.get((chat_id, user_id))
    return data["token"] if data else None


def check_answer(chat_id, user_id, answer):
    """پاسخ را فقط برای همان کاربری که چیستان را گرفته بررسی می‌کند."""
    key = (chat_id, user_id)
    data = active_riddles.get(key)
    if not data:
        return False

    if time.time() - data["time"] > RIDDLE_TIMEOUT:
        # زمان تمام شده: پاسخ درست هم امتیاز نمی‌گیرد و state پاک می‌شود.
        del active_riddles[key]
        return False

    if _norm(answer) == _norm(data["answer"]):
        # پاک کردن پیش از بازگشت: هر چیستان فقط یک بار سکه می‌دهد.
        del active_riddles[key]
        return True
    return False


def get_answer(chat_id, user_id):
    data = active_riddles.get((chat_id, user_id))
    return data["answer"] if data else None


def clear(chat_id, user_id, token=None):
    """پایان دادن به چیستان فعال؛ فقط اگر توکن همان دور باشد.

    تایمرِ دورِ قبلی نمی‌تواند پاسخ دور جدید را لو بدهد.
    """
    key = (chat_id, user_id)
    data = active_riddles.get(key)
    if not data or (token is not None and data["token"] != token):
        return None
    del active_riddles[key]
    return data["answer"]
