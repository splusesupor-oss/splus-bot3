_used_jokes = {}


def get_joke(chat_id=None):
    """تا پایان بانک، برای هر گروه جک تکراری برنمی‌گرداند."""
    key = chat_id if chat_id is not None else "__default__"
    used = _used_jokes.setdefault(key, set())
    available = [index for index in range(len(JOKES)) if index not in used]
    if not available:
        used.clear()
        available = list(range(len(JOKES)))
    index = random.SystemRandom().choice(available)
    used.add(index)
    return JOKES[index]
