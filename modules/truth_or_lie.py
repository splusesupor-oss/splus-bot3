def total_statements():
    return len(STATEMENTS)


def is_active(chat_id):
    return chat_id in _ACTIVE


def current(chat_id):
    state = _ACTIVE.get(chat_id)
    return dict(state) if state else None


def start(chat_id):
    """سوال جدید. None اگر همین حالا سوالی باز است."""
    if chat_id in _ACTIVE:
        return None
    seen = _SEEN.setdefault(chat_id, set())
    remaining = [i for i in range(len(STATEMENTS)) if i not in seen]
    if not remaining:
        seen.clear()
        remaining = list(range(len(STATEMENTS)))
    index = _RANDOM.choice(remaining)
    seen.add(index)
    state = {
        "token": f"{int(time.time() * 1000)}",
        "index": index,
        "deadline": time.monotonic() + ANSWER_SECONDS,
    }
    _ACTIVE[chat_id] = state
    text, _truth = STATEMENTS[index]
    return {"token": state["token"], "question": text}


def _parse_guess(text):
    """تبدیل پاسخ کاربر به True/False؛ None اگر پاسخ این بازی نیست."""
    value = str(text or "").strip().translate(_PERSIAN_DIGITS)
    # ایموجی‌های کیبورد مثل 1️⃣ و 2️⃣ هم پذیرفته می‌شوند
    # (حذف variation selector و keycap).
    value = value.replace("\ufe0f", "").replace("\u20e3", "")
    normalized = " ".join(value.replace("ي", "ی").split())
    if normalized in {"1", TRUE_WORD, "حقیقته", "درست", "درسته", "راست", "راسته"}:
        return True
    if normalized in {"2", LIE_WORD, "دروغه", "غلط", "غلطه", "نادرست"}:
        return False
    return None


def answer(chat_id, user_id, text):
    """بررسی پاسخ. خروجی dict نتیجه یا None اگر پیام پاسخ بازی نیست.

    ⚠️ عمداً هیچ چک مهلتی اینجا نیست: تا وقتی سوال باز است (تایمر ۲۵
    ثانیه هنوز آن را نبسته) پاسخ پذیرفته می‌شود. چک سخت‌گیرانهٔ
    deadline باعث می‌شد در گروه‌های شلوغ که پیام چند ثانیه در صف
    می‌ماند، جوابِ به‌موقعِ کاربر بی‌صدا رد شود و نه سکه بیاید و نه
    پیام «اشتباه بود».
    """
    state = _ACTIVE.get(chat_id)
    if not state:
        return None
    guess = _parse_guess(text)
    if guess is None:
        return None
    _ACTIVE.pop(chat_id, None)
    statement, truth = STATEMENTS[state["index"]]
    return {
        "token": state["token"],
        "user_id": user_id,
        "correct": guess == truth,
        "truth": truth,
        "truth_label": TRUE_WORD if truth else LIE_WORD,
        "question": statement,
    }


def timeout(chat_id, token):
    """بستن سوال بعد از ۲۵ ثانیه؛ جواب صحیح را برمی‌گرداند."""
    state = _ACTIVE.get(chat_id)
    if not state or state["token"] != token:
        return None
    _ACTIVE.pop(chat_id, None)
    statement, truth = STATEMENTS[state["index"]]
    return {
        "truth_label": TRUE_WORD if truth else LIE_WORD,
        "question": statement,
    }


def cancel(chat_id):
    _ACTIVE.pop(chat_id, None)


def reset_all(chat_id=None):
    if chat_id is None:
        _ACTIVE.clear()
        _SEEN.clear()
    else:
        _ACTIVE.pop(chat_id, None)
        _SEEN.pop(chat_id, None)
