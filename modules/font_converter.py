def make_fonts(text):
    """Return only character-conversion font styles, never decorative frames."""
    return [
        bold(text),
        mono(text),
        italic(text),
        bubble(text),
        wide(text),
        upside(text),
        small(text),
        double(text),
        math_italic(text),
        math_bold_italic(text),
        script(text),
        fraktur(text),
        bold_fraktur(text),
        sans_bold_italic(text),
    ]
